    /** The picture for a section (16x16 RGB, -1 = see-through); unknown sections get a coin. */
    static int[] icon(String section, String material) {
        Art a = ART.get(section);
        if (a == null) a = ART.get("buycoins");
        int[] out = new int[256];
        for (int y = 0; y < 16; y++) {
            String row = y < a.rows().length ? a.rows()[y] : "";
            for (int x = 0; x < 16; x++) {
                char ch = x < row.length() ? row.charAt(x) : '.';
                Integer c = a.colors().get(ch);
                out[y * 16 + x] = c == null ? -1 : c;
            }
        }
        return out;
    }
